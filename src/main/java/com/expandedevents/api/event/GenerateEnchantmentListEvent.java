package com.expandedevents.api.event;

import net.minecraft.enchantment.Enchantment;
import net.minecraft.enchantment.EnchantmentData;
import net.minecraft.entity.player.EntityPlayer;
import net.minecraft.item.ItemStack;
import net.minecraft.util.math.BlockPos;
import net.minecraft.world.World;
import net.minecraftforge.event.entity.player.PlayerEvent;
import net.minecraftforge.fml.common.eventhandler.Cancelable;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/**
 * This event is fired when an Enchanting Table generates a list of enchantments that will be used to populate
 * the enchanting table enchantments view.
 * <p>
 * This event is not {@link Cancelable}.<br>
 * This Event does not have a {@link Result}.<br>
 * This event is fired on the {@link net.minecraftforge.common.MinecraftForge#EVENT_BUS}.
 */
public class GenerateEnchantmentListEvent extends PlayerEvent {
    private final World world;
    private final BlockPos pos;
    private final ItemStack stack;
    private final ItemStack reagent;
    private final int xpSeed;
    private final int enchantTier;
    private final int originalEnchantmentLevel;
    private int enchantmentLevel;
    private int levelCost;
    private int reagentCost;
    private final List<EnchantmentData> originalEnchants;
    private List<EnchantmentData> unmodifiableEnchants;
    private List<EnchantmentData> modifiableEnchants;

    public GenerateEnchantmentListEvent(World world, BlockPos pos, EntityPlayer player, ItemStack toEnchant, ItemStack reagent, int xpSeed, int enchantTier, int enchantmentLevel, List<EnchantmentData> enchants) {
        super(player);
        this.world = world;
        this.pos = pos;
        this.stack = toEnchant;
        this.reagent = reagent;
        this.xpSeed = xpSeed;
        this.enchantTier = enchantTier;
        this.originalEnchantmentLevel = this.enchantmentLevel = enchantmentLevel;
        this.levelCost = this.reagentCost = enchantTier + 1;
        this.unmodifiableEnchants = this.originalEnchants = enchants;
    }

    /**
     * Returns the enchanting table world object.
     */
    public World getWorld()
    {
        return world;
    }

    /**
     * Returns the position of the enchanting table.
     */
    public BlockPos getPos()
    {
        return pos;
    }

    /**
     * Returns the ItemStack that will be enchanted.
     */
    public ItemStack getStack() {
        return stack;
    }

    /**
     * Returns the reagent in the lapis lazuli slot used to enchant the item.
     */
    public ItemStack getReagent() {
        return reagent;
    }

    /**
     *
     */
    public int getXpSeed() {
        return xpSeed;
    }

    /**
     * Returns the enchanting table slot these enchants will apply to.
     */
    public int getEnchantTier() {
        return enchantTier;
    }

    /**
     * Returns the original value of the required player level for this enchantment tier.
     */
    public int getOriginalRequiredLevel() {
        return originalEnchantmentLevel;
    }

    /**
     * Returns the required player level to access this enchantment tier. Changing this value
     * modifies the level requirement <strong>after</strong> the first enchantment list
     * is generated.
     * <p>
     * To modify the enchantment value prior to the enchantment list being generated, use
     * {@link net.minecraftforge.event.enchanting.EnchantmentLevelSetEvent}.
     */
    public int getRequiredLevel() {
        return enchantmentLevel;
    }

    /**
     * Sets the required level the player needs to access this enchantment tier.
     */
    public void setRequiredLevel(int playerLevel) {
        this.enchantmentLevel = playerLevel;
    }

    /**
     * Gets the number of levels consumed when enchanting an item from this enchantment tier.
     */
    public int getLevelCost() {
        return levelCost;
    }

    /**
     * Sets the number of levels required to enchant an item from this enchantment tier.
     * <p>
     * Note that the experience levels that appear on the enchanting table Gui are part
     * of the table texture, so they will not update should the level cost change.
     */
    public void setLevelCost(int levelCost) {
        this.levelCost = levelCost;
    }

    /**
     * Returns the enchanting reagent cost (generally Lapis Lazuli) for this enchantment tier.
     */
    public int getReagentCost() {
        return reagentCost;
    }

    /**
     * Sets a new enchanting reagent cost for this enchantment tier.
     * @param reagentCost The number of items that will be consumed on successful enchant
     */
    public void setReagentCost(int reagentCost) {
        this.reagentCost = reagentCost;
    }

    /**
     * Returns a list of the original enchantments generated by the enchanting table before
     * any changes from other event listeners.
     */
    public List<EnchantmentData> getOriginalEnchantments() {
        return originalEnchants;
    }

    /**
     * Returns an unmodifiable view of the enchantments. Use other methods from this event to
     * modify the possible enchantments.
     */
    public List<EnchantmentData> getEnchantments() {
        return this.unmodifiableEnchants;
    }

    /**
     * Returns a modifiable instance of the enchantment list, creating a new instance if the
     * current map is unmodifiable.
     */
    public List<EnchantmentData> getModifiableEnchantments() {
        if(modifiableEnchants == null) {
            this.modifiableEnchants = new ArrayList<>(this.originalEnchants);
            this.unmodifiableEnchants = Collections.unmodifiableList(this.modifiableEnchants);
        }
        return modifiableEnchants;
    }

    /**
     * Adds a new enchantment to the enchantment list.
     * @param enchantment The enchantment to add
     * @param level The enchantment level
     */
    public void addEnchantment(Enchantment enchantment, int level) {
        addEnchantment(new EnchantmentData(enchantment, level));
    }

    /**
     * Adds a new enchantment to the enchantment list. This method is the same as {@link GenerateEnchantmentListEvent#addEnchantment(Enchantment, int)}
     * but allows custom {@link EnchantmentData} logic if desired.
     * @param enchantmentData The enchantment data
     */
    public void addEnchantment(EnchantmentData enchantmentData) {
        this.getModifiableEnchantments().add(enchantmentData);
    }

    /**
     * Removes all instances of an enchantment from the enchantment list.
     * @param enchantment The enchantment to remove
     */
    public void removeEnchantment(Enchantment enchantment) {
        this.getModifiableEnchantments().removeIf(data -> data.enchantment == enchantment);
    }

    /**
     * Removes all enchantments
     */
    public void clearEnchantments() {
        this.getModifiableEnchantments().clear();
    }
}
